"""Part polygons for the pests (front view first; back/side are added once those images are cut). python art/doll/make_pest_specs.py"""
import json, os
D = os.path.dirname(__file__)
def spec(name, view, parts):
    json.dump({"parts": [dict(name=n, poly=p, pivot=pv, parent=par, order=o) for n, p, pv, par, o in parts]},
              open(os.path.join(D, name, view + "_spec.json"), "w"), indent=1)
def mirror(poly, w): return [[w - x, y] for x, y in poly]

def front(name, W, head, torso, armL, shL, shR, hipY, kneeY, hipL, hipR, kneeL, kneeR, headPivot, torsoPivot, view="front"):
    spec(name, view, [
     ("thighL", [[0, hipY], [W / 2, hipY], [W / 2, kneeY], [0, kneeY]], hipL, None, 1),
     ("thighR", [[W / 2, hipY], [W, hipY], [W, kneeY], [W / 2, kneeY]], hipR, None, 1),
     ("shinL", [[0, kneeY], [W / 2, kneeY], [W / 2, 768], [0, 768]], kneeL, "thighL", 0),
     ("shinR", [[W / 2, kneeY], [W, kneeY], [W, 768], [W / 2, 768]], kneeR, "thighR", 0),
     ("torso", torso, torsoPivot, None, 5),
     ("armL", armL, shL, "torso", 6),
     ("armR", mirror(armL, W), shR, "torso", 6),
     ("head", head, headPivot, "torso", 7),
    ])

